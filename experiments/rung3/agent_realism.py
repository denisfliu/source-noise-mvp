"""Motion realism of the agent-in-the-loop flights vs the real demonstrations (2026-10-07).

For every Table 2 evaluation flight (Sonnet t11-15, Opus t21-25; mannequin, orbit, left_mannequin) and for the 100 real
demonstrations, per-flight statistics at the 10 Hz control rate: median moving speed (steps above 0.05 m/s), 95th
percentile of speed, acceleration, jerk and yaw rate. Each cell reports the median over flights. The simulator is
kinematic (position += action), so motion the real drone could not track costs nothing in simulation; these numbers
are how far each arm's flights are from what a pilot actually flew.

  python3 agent_realism.py          # prints the table and writes agent_eval/realism.md
"""
import glob, json, os

import numpy as np

RD = os.path.dirname(os.path.abspath(__file__)); RUN = "/home/dfliu/ctxrun"; DT = 0.1
TASKS = ("mannequin", "orbit", "left_mannequin")
CELLS = [("Sonnet + waypoints", "_waypoints", range(11, 16)), ("Sonnet + ours", "_ours", range(11, 16)),
         ("Opus + waypoints", "_waypoints_claude-opus-5", range(21, 26)), ("Opus + ours", "_ours_opus", range(21, 26))]
COLS = [("spd_med", "speed median (m/s)", "{:.2f}"), ("spd_p95", "speed p95 (m/s)", "{:.2f}"),
        ("acc_p95", "accel p95 (m/s²)", "{:.2f}"), ("jerk_p95", "jerk p95 (m/s³)", "{:.1f}"),
        ("yaw_p95", "yaw rate p95 (°/s)", "{:.0f}")]


def stats(P, yaw):
    v = np.diff(P, axis=0) / DT; s = np.linalg.norm(v, axis=1)
    a = np.diff(v, axis=0) / DT; j = np.diff(a, axis=0) / DT
    yr = np.degrees(np.abs(np.diff(np.unwrap(yaw)))) / DT
    return dict(spd_med=float(np.median(s[s > 0.05])) if (s > 0.05).any() else 0.0, spd_p95=float(np.percentile(s, 95)),
                acc_p95=float(np.percentile(np.linalg.norm(a, axis=1), 95)),
                jerk_p95=float(np.percentile(np.linalg.norm(j, axis=1), 95)), yaw_p95=float(np.percentile(yr, 95)))


def median_of(rows):
    return {k: float(np.median([r[k] for r in rows])) for k in rows[0]}


def main():
    real = [stats((s := np.load(f)["state"].astype(float))[:, :3], s[:, 3]) for f in sorted(glob.glob(f"{RD}/data_gate_real/ep_*.npz"))]
    table = [(f"Real demos ({len(real)})", median_of(real))]
    for name, suf, trials in CELLS:
        rows = []
        for t in TASKS:
            for r in map(json.loads, open(f"{RD}/agent_eval/{t}{suf}.jsonl")):
                if r["trial"] in trials:
                    T = np.load(f"{RUN}/{r['traj']}").astype(float); rows.append(stats(T[:, :3], T[:, 3]))
        table.append((f"{name} ({len(rows)})", median_of(rows)))
    md = ["| flights | " + " | ".join(c[1] for c in COLS) + " |", "|---" * (len(COLS) + 1) + "|"]
    md += [f"| {n} | " + " | ".join(fmt.format(v[k]) for k, _, fmt in COLS) + " |" for n, v in table]
    text = "\n".join(md)
    with open(f"{RD}/agent_eval/realism.md", "w") as fh:
        fh.write("# Motion realism of the agent flights (generated by experiments/rung3/agent_realism.py)\n\n"
                 "Per-flight statistics at 10 Hz, median over flights. The simulator is kinematic, so motion the real\n"
                 "drone could not track costs nothing in simulation.\n\n" + text + "\n")
    print(text)


if __name__ == "__main__":
    main()
